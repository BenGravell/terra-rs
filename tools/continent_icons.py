"""Generate continent pictograms from the bundled public-domain Natural Earth map.

Run: uv run tools/continent_icons.py
"""
import json
import math
from pathlib import Path

from shapely import affinity
from shapely.geometry import box, shape
from shapely.ops import transform, unary_union

ROOT = Path(__file__).resolve().parents[1]
NAMES = ["Africa", "Asia", "Europe", "Oceania", "North America", "South America"]
groups = {name: [] for name in NAMES}
features = json.loads((ROOT / "data/raw/ne_110m_admin_0_countries.geojson").read_text())["features"]
for feature in features:
    name = feature["properties"]["CONTINENT"]
    if name not in groups:
        continue
    geometry = shape(feature["geometry"])
    # Natural Earth assigns all of Russia to Europe; divide it at the Urals.
    if feature["properties"]["ADMIN"] == "Russia":
        groups["Europe"].append(geometry.intersection(box(-180, -90, 60, 90)))
        groups["Asia"].append(geometry.intersection(box(60, -90, 180, 90)))
        groups["Asia"].append(geometry.intersection(box(-180, -90, -160, 90)))
        continue
    groups[name].append(geometry)

output = ["// Generated by tools/continent_icons.py from Natural Earth 1:110m (public domain).", "["]
for name in NAMES:
    geometry = unary_union(groups[name])
    if name == "Europe":
        # Exclude overseas territories from the European pictogram.
        geometry = geometry.intersection(box(-30, 34, 60, 82))
    if name in ("Asia", "Oceania"):
        geometry = transform(lambda x, y, z=None: (x + 360 if x < 0 else x, y), geometry)
    elif name == "North America":
        geometry = transform(lambda x, y, z=None: (x - 360 if x > 0 else x, y), geometry)
    polygons = list(geometry.geoms) if geometry.geom_type == "MultiPolygon" else [geometry]
    # Retain islands that are visible at icon size; omit remote specks.
    polygons = [polygon for polygon in polygons if polygon.area >= 0.8]
    geometry = unary_union(polygons)
    left, bottom, right, top = geometry.bounds
    geometry = affinity.scale(geometry, xfact=math.cos(math.radians((bottom + top) / 2)), yfact=-1, origin=(0, 0))
    left, bottom, right, top = geometry.bounds
    scale = 30 / max(right - left, top - bottom)
    geometry = affinity.translate(geometry, xoff=-(left + right) / 2, yoff=-(bottom + top) / 2)
    geometry = affinity.scale(geometry, xfact=scale, yfact=scale, origin=(0, 0))
    geometry = affinity.translate(geometry, xoff=16, yoff=16)
    # Work in display pixels: close subpixel inlets and discard invisible detail.
    geometry = geometry.buffer(0.35).buffer(-0.35).simplify(0.45, preserve_topology=True)
    polygons = list(geometry.geoms) if geometry.geom_type == "MultiPolygon" else [geometry]
    polygons = [
        polygon for polygon in polygons
        if polygon.area >= 3.
        and min(polygon.bounds[2] - polygon.bounds[0], polygon.bounds[3] - polygon.bounds[1]) >= 1.5
    ]
    assert polygons, f"No visible outline for {name}"
    output.append(f"    // {name}")
    output.append("    &[")
    for polygon in sorted(polygons, key=lambda polygon: -polygon.area):
        coords = ", ".join(f"[{x:.2f}, {y:.2f}]" for x, y in polygon.exterior.coords)
        output.append(f"        &[{coords}],")
    output.append("    ],")
output.append("]")
(ROOT / "assets/continent_outlines.rs").write_text("\n".join(output) + "\n")
